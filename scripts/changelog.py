#!/usr/bin/env python3
"""Conventional-commit changelog + release-notes generator (stdlib only).

release-please-style output: linked version headings, linked commit shas,
linked PR numbers, @-linked contributors.

Usage:
    changelog.py changelog --tag vX.Y.Z   # prepend section to CHANGELOG.md
    changelog.py notes <tag>              # print release notes for <tag>
    changelog.py suggest                  # print suggested bump: major|minor|patch
"""
from __future__ import annotations

import datetime
import re
import subprocess
import sys
from pathlib import Path

GROUPS = [
    ("feat", "Features"),
    ("fix", "Bug Fixes"),
    ("perf", "Performance"),
    ("revert", "Reverts"),
    ("refactor", "Refactoring"),
    ("docs", "Documentation"),
    ("ci", "CI/CD"),
    ("test", "Tests"),
    ("build", "Build"),
    ("chore", "Chores"),
    ("other", "Other Changes"),
]
CONVENTIONAL = re.compile(
    r"^(?P<type>\w+)(?:\((?P<scope>[^)]*)\))?(?P<bang>!)?:\s*(?P<desc>.+)$")
PR_REF = re.compile(r"#(\d+)")

HEADER = """# Changelog

All notable changes to this project are documented here.
Format follows [Keep a Changelog](https://keepachangelog.com/en/1.1.0/);
versions follow [SemVer](https://semver.org/). Generated by
`scripts/changelog.py` from conventional commits.
"""

_REPO: str | None = None
_LOGIN_CACHE: dict[str, str | None] = {}


def _git(*args: str) -> str:
    r = subprocess.run(["git", *args], capture_output=True, text=True,
                       encoding="utf-8")
    if r.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)}: {r.stderr.strip()}")
    return r.stdout


def repo() -> str:
    """owner/repo parsed from origin, e.g. 'JoShMiQueL/devin-proxy'."""
    global _REPO
    if _REPO is None:
        url = _git("remote", "get-url", "origin").strip()
        m = re.search(r"github\.com[:/]([^/]+/[^/.]+?)(?:\.git)?$", url)
        _REPO = m.group(1) if m else "owner/repo"
    return _REPO


def gh_url(*parts: str) -> str:
    return f"https://github.com/{repo()}/{'/'.join(parts)}"


def gh_login(sha: str) -> str | None:
    """GitHub username for a commit, via `gh api`; None if unavailable."""
    if sha in _LOGIN_CACHE:
        return _LOGIN_CACHE[sha]
    try:
        r = subprocess.run(
            ["gh", "api", f"repos/{repo()}/commits/{sha}",
             "--jq", ".author.login"],
            capture_output=True, text=True, timeout=10)
        login = r.stdout.strip() if r.returncode == 0 else ""
        _LOGIN_CACHE[sha] = login if login and login != "null" else None
    except Exception:
        _LOGIN_CACHE[sha] = None
    return _LOGIN_CACHE[sha]


def tags() -> list[str]:
    return [t for t in _git("tag", "--sort=-v:refname").splitlines() if t]


def last_tag() -> str | None:
    t = tags()
    return t[0] if t else None


def commits(range_spec: str) -> list[dict]:
    out = _git("log", "--format=%H%x1f%an%x1f%ae%x1f%B%x1e", range_spec)
    items = []
    for rec in out.split("\x1e"):
        rec = rec.strip()
        if not rec:
            continue
        sha, author, email, body = rec.split("\x1f", 3)
        first = body.strip().splitlines()[0]
        if first.startswith("release:"):
            continue  # bookkeeping commits are not changelog content
        m = CONVENTIONAL.match(first)
        breaking = "BREAKING CHANGE" in body or "BREAKING-CHANGE" in body
        if m:
            typ, scope, desc = m["type"], m["scope"], m["desc"]
            breaking = breaking or bool(m["bang"])
        else:
            typ, scope, desc = "other", None, first
        items.append({
            "sha": sha, "author": author, "email": email,
            "type": typ, "scope": scope, "desc": desc.strip(),
            "breaking": breaking,
        })
    return items


def tag_range(tag: str) -> str:
    """prev_tag..tag — the commits that belong to release `tag`."""
    all_tags = tags()
    if tag in all_tags:
        idx = all_tags.index(tag)
        if idx + 1 < len(all_tags):
            return f"{all_tags[idx + 1]}..{tag}"
        return tag
    return f"{last_tag()}..HEAD" if last_tag() else "HEAD"


def release_range(tag: str) -> str:
    """tag_range but resilient to tags pointing at non-ancestor commits."""
    rng = tag_range(tag)
    if ".." not in rng:
        return rng
    base, tip = rng.split("..", 1)
    if tip == tag:
        tagged = subprocess.run(
            ["git", "rev-parse", f"{tag}^{{commit}}"],
            capture_output=True, text=True, encoding="utf-8").stdout.strip()
        if subprocess.run(["git", "merge-base", "--is-ancestor",
                           tagged, "HEAD"]).returncode != 0:
            return f"{base}..HEAD"
    return rng


def prev_tag(tag: str) -> str | None:
    all_tags = tags()
    if tag in all_tags:
        idx = all_tags.index(tag)
        return all_tags[idx + 1] if idx + 1 < len(all_tags) else None
    return last_tag()


def suggest(commits_: list[dict]) -> str:
    if any(c["breaking"] for c in commits_):
        return "major"
    if any(c["type"] == "feat" for c in commits_):
        return "minor"
    return "patch"


def group(commits_: list[dict]) -> dict[str, list[dict]]:
    order = {t: i for i, (t, _) in enumerate(GROUPS)}
    label = dict(GROUPS)
    g: dict[str, list[dict]] = {}
    for c in commits_:
        g.setdefault(label.get(c["type"], "Other Changes"), []).append(c)
    return dict(sorted(g.items(), key=lambda kv: order.get(
        next((t for t, lbl in GROUPS if lbl == kv[0]), "other"), 99)))


def _link_refs(text: str) -> str:
    """#123 -> [#123](…/pull/123)."""
    return PR_REF.sub(lambda m: f"[{m.group(0)}]({gh_url('pull', m.group(1))})",
                      text)


def fmt_commit(c: dict) -> str:
    scope = f"**{c['scope']}:** " if c["scope"] else ""
    desc = _link_refs(c["desc"])
    sha8 = c["sha"][:8]
    return (f"* {scope}{desc} "
            f"([{sha8}]({gh_url('commit', c['sha'])}))")


def heading(tag: str, date: str) -> str:
    ver = tag.lstrip("v")
    prev = prev_tag(tag)
    target = (gh_url("compare", f"{prev}...{tag}") if prev
              else gh_url("releases", "tag", tag))
    return f"## [{ver}]({target}) ({date})"


def contributor_list(commits_: list[dict]) -> list[dict]:
    """Unique authors: {name, login|None} ordered by first appearance."""
    seen: dict[str, dict] = {}
    for c in commits_:
        if c["email"] not in seen:
            seen[c["email"]] = {"name": c["author"],
                                "login": gh_login(c["sha"])}
    return list(seen.values())


def _contrib_line(a: dict, c: dict | None = None) -> str:
    who = (f"[@{a['login']}](https://github.com/{a['login']})"
           if a["login"] else a["name"])
    if c is None:
        return f"* {who}"
    return (f"* {who} made their first contribution in "
            f"[{c['sha'][:8]}]({gh_url('commit', c['sha'])})")


def new_contributors(tag: str, commits_: list[dict]) -> list[tuple[dict, dict]]:
    """(author, first_commit) pairs that never committed before this tag."""
    rng = tag_range(tag)
    if ".." not in rng:
        return []  # first tag: everyone is new, section not meaningful
    base = rng.split("..")[0]
    prior = set(subprocess.run(
        ["git", "log", "--format=%ae", base],
        capture_output=True, text=True, encoding="utf-8").stdout.split())
    first: dict[str, dict] = {}
    for c in reversed(commits_):  # oldest first
        first[c["email"]] = c
    out = []
    for email, c in first.items():
        if email not in prior:
            a = {"name": c["author"], "login": gh_login(c["sha"])}
            out.append((a, c))
    return out


def section(tag: str, commits_: list[dict], date: str) -> str:
    lines = [heading(tag, date), ""]
    brk = [c for c in commits_ if c["breaking"]]
    if brk:
        lines += ["### ⚠ BREAKING CHANGES", ""]
        lines += [f"* {_link_refs(c['desc'])}" for c in brk] + [""]
    for label, items in group(commits_).items():
        lines += [f"### {label}", ""]
        lines += [fmt_commit(c) for c in items] + [""]
    return "\n".join(lines)


def cmd_changelog(tag: str) -> None:
    path = Path("CHANGELOG.md")
    cur = commits(f"{last_tag()}..HEAD" if last_tag() else "HEAD")
    if not cur:
        print("no commits since last tag", file=sys.stderr)
        sys.exit(1)
    sec = section(tag, cur, datetime.date.today().isoformat())
    old = path.read_text(encoding="utf-8") if path.exists() else HEADER
    head_end = old.find("\n## [")
    header = old[:head_end] if head_end != -1 else old.rstrip() + "\n"
    if not header.startswith("# Changelog"):
        header = HEADER
    rest = old[head_end:] if head_end != -1 else ""
    path.write_text(header.rstrip() + "\n\n" + sec + rest, encoding="utf-8")
    print(f"CHANGELOG.md updated with [{tag}] ({len(cur)} commits)")


def cmd_notes(tag: str) -> None:
    cur = commits(release_range(tag))
    out = section(tag, cur, datetime.date.today().isoformat())
    new = new_contributors(tag, cur)
    if new:
        out += "\n### New Contributors\n\n" + \
               "\n".join(_contrib_line(a, c) for a, c in new) + "\n"
    else:
        contrib = contributor_list(cur)
        if contrib:
            out += "\n### Contributors\n\n" + \
                   "\n".join(_contrib_line(a) for a in contrib) + "\n"
    print(out)


def main() -> None:
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        sys.exit(1)
    cmd = sys.argv[1]
    if cmd == "changelog":
        tag = sys.argv[sys.argv.index("--tag") + 1] if "--tag" in sys.argv else None
        if not tag:
            print("changelog needs --tag vX.Y.Z", file=sys.stderr)
            sys.exit(1)
        cmd_changelog(tag)
    elif cmd == "notes":
        cmd_notes(sys.argv[2])
    elif cmd == "suggest":
        print(suggest(commits(f"{last_tag()}..HEAD" if last_tag() else "HEAD")))
    else:
        print(__doc__, file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
